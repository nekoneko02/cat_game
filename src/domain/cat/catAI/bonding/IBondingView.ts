/**
 * なつき度View インターフェース
 *
 * 外部パッケージから「ねこ.ねこAI.なつき」パッケージ内のなつき度にアクセスするための
 * 公開インターフェース。パッケージ可視性の原則に従い、なつきパッケージの実装詳細を
 * 隠蔽しながら必要な情報のみを公開する。
 *
 * @package ねこ
 */
export interface IBondingView {
  /**
   * なつきレベルを取得
   * @returns なつきレベル (0~10)
   */
  getLevel(): number;

  /**
   * なつきゲージ値を取得
   * @returns なつきゲージ値 (0~1)
   */
  getGauge(): number;
}
